import type { Issue, Severity } from './issues'
import type { ValidationResult } from './validate'

const SEVERITIES: Severity[] = ['error', 'warning', 'info']

interface Group {
  severity: Severity
  category: Issue['category']
  collection: string
  rule: string
  pathPattern: string
  issues: Issue[]
}

const pattern = (path?: string) => (path ?? '').replace(/\[\d+\]/g, '[]')

export function groupIssues(issues: Issue[]): Group[] {
  const map = new Map<string, Group>()
  for (const i of issues) {
    const key = [i.severity, i.category, i.collection, i.rule, pattern(i.path)].join('|')
    if (!map.has(key)) map.set(key, { severity: i.severity, category: i.category, collection: i.collection, rule: i.rule, pathPattern: pattern(i.path), issues: [] })
    map.get(key)!.issues.push(i)
  }
  return [...map.values()].sort((a, b) => b.issues.length - a.issues.length)
}

export function countBy(issues: Issue[], key: (i: Issue) => string) {
  const out = new Map<string, Record<Severity, number>>()
  for (const i of issues) {
    const k = key(i)
    if (!out.has(k)) out.set(k, { error: 0, warning: 0, info: 0 })
    out.get(k)![i.severity]++
  }
  return out
}

const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/</g, '&lt;').replace(/\n/g, ' ')

/** Markdown report: summary tables, then every error/warning group with its records, then info as counts. */
export function renderMarkdown(result: ValidationResult, opts: { title: string, command: string, examples?: number }): string {
  const max = opts.examples ?? 15
  const { issues, counts } = result
  const lines: string[] = [`# ${opts.title}`, '', `Generated by \`${opts.command}\`.`, '']
  const total = countBy(issues, () => 'all').get('all') ?? { error: 0, warning: 0, info: 0 }
  const records = Object.values(counts).reduce((a, b) => a + b, 0)
  lines.push(`**${records} records** in ${Object.keys(counts).length} collections. **${total.error} errors**, **${total.warning} warnings**, ${total.info} info.`, '')

  lines.push('## By category', '', '| Category | Errors | Warnings | Info |', '|---|---:|---:|---:|')
  for (const [cat, c] of [...countBy(issues, i => i.category)].sort()) lines.push(`| ${cat} | ${c.error} | ${c.warning} | ${c.info} |`)
  lines.push('')

  lines.push('## By type', '', '| Type | Records | Errors | Warnings | Info |', '|---|---:|---:|---:|---:|')
  const byCol = countBy(issues, i => i.collection)
  for (const col of Object.keys(counts).sort()) {
    const c = byCol.get(col) ?? { error: 0, warning: 0, info: 0 }
    lines.push(`| ${col} | ${counts[col]} | ${c.error} | ${c.warning} | ${c.info} |`)
  }
  lines.push('')

  const groups = groupIssues(issues)
  for (const severity of ['error', 'warning'] as const) {
    const sevGroups = groups.filter(g => g.severity === severity)
    lines.push(`## ${severity === 'error' ? 'Errors' : 'Warnings'} by type`, '')
    if (!sevGroups.length) lines.push('None.', '')
    const cols = [...new Set(sevGroups.map(g => g.collection))].sort()
    for (const col of cols) {
      const colGroups = sevGroups.filter(g => g.collection === col)
      const n = colGroups.reduce((a, g) => a + g.issues.length, 0)
      lines.push(`### ${col} (${n})`, '')
      for (const g of colGroups) {
        const where = g.pathPattern ? ` at \`${g.pathPattern}\`` : ''
        lines.push(`- **${g.rule}**${where} (${g.category}): ${g.issues.length}`)
        for (const i of g.issues.slice(0, max)) {
          lines.push(`  - \`${i.id ?? i.file ?? '?'}\`${i.path && pattern(i.path) !== i.path ? ` \`${i.path}\`` : ''}: ${esc(i.message)}`)
        }
        if (g.issues.length > max) lines.push(`  - …and ${g.issues.length - max} more`)
      }
      lines.push('')
    }
  }

  lines.push('## Info (counts only)', '', '| Rule | Category | Count | Types |', '|---|---|---:|---|')
  const info = new Map<string, { category: string, n: number, cols: Set<string> }>()
  for (const i of issues.filter(x => x.severity === 'info')) {
    const k = i.rule
    if (!info.has(k)) info.set(k, { category: i.category, n: 0, cols: new Set() })
    const e = info.get(k)!
    e.n += i.rule.startsWith('tag:') ? Number(i.message.match(/^(\d+)×/)?.[1] ?? 1) : 1
    e.cols.add(i.collection)
  }
  for (const [rule, e] of [...info].sort((a, b) => b[1].n - a[1].n)) lines.push(`| ${esc(rule)} | ${e.category} | ${e.n} | ${[...e.cols].sort().join(', ')} |`)
  lines.push('')
  return lines.join('\n')
}

export function renderText(result: ValidationResult): string {
  const groups = groupIssues(result.issues.filter(i => i.severity !== 'info'))
  const out = groups.map(g => `${g.severity.toUpperCase().padEnd(7)} ${g.collection}: ${g.rule}${g.pathPattern ? ` @ ${g.pathPattern}` : ''} ×${g.issues.length}`)
  const t = countBy(result.issues, () => 'all').get('all') ?? { error: 0, warning: 0, info: 0 }
  out.push('', `${t.error} errors, ${t.warning} warnings, ${t.info} info`)
  return out.join('\n')
}

export { SEVERITIES }

const BACKLOG_TITLES: Record<string, string> = {
  'note-only:global-note': 'Sheet notes standing in for a feature (`global-note`)',
  'note-only:speed-note': 'Movement rules written as text (`speed-note`)',
  'note-only:text-action': 'Actions with only a description (no damage, DC, attack, range or toggle)',
  'note-only:rider-note': 'Hit/save riders written in `notes`',
  'note-only:prose-only': 'Features, traits, feats and edges with no mechanics at all',
}

/** Markdown worklist of rules that exist only as text, grouped by kind then type. */
export function renderBacklog(result: ValidationResult, opts: { title: string, command: string, linkPrefix?: string }): string {
  const items = result.issues.filter(i => i.category === 'backlog')
  const lines = [`# ${opts.title}`, '', `Generated by \`${opts.command}\`.`, '']
  const kinds = Object.keys(BACKLOG_TITLES)
  const cols = [...new Set(items.map(i => i.collection))].sort()
  lines.push(`| Kind | ${cols.join(' | ')} | Total |`, `|---|${cols.map(() => '---:').join('|')}|---:|`)
  for (const k of kinds) {
    const ofKind = items.filter(i => i.rule === k)
    lines.push(`| ${k.replace('note-only:', '')} | ${cols.map(c => ofKind.filter(i => i.collection === c).length || '').join(' | ')} | ${ofKind.length} |`)
  }
  lines.push('')
  for (const k of kinds) {
    const ofKind = items.filter(i => i.rule === k)
    if (!ofKind.length) continue
    lines.push(`## ${BACKLOG_TITLES[k]} (${ofKind.length})`, '')
    for (const c of [...new Set(ofKind.map(i => i.collection))].sort()) {
      const ofCol = ofKind.filter(i => i.collection === c)
      lines.push(`### ${c} (${ofCol.length})`, '')
      for (const i of ofCol) {
        const label = opts.linkPrefix && i.file ? `[\`${i.id}\`](${opts.linkPrefix}${i.file})` : `\`${i.id}\``
        lines.push(`- [ ] ${label}${i.path ? ` \`${i.path}\`` : ''}: ${esc(i.message)}`)
      }
      lines.push('')
    }
  }
  return lines.join('\n')
}
